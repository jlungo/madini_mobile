import '../../domain/entities/deposit_entity.dart';

class DepositModel extends DepositEntity {
  const DepositModel({
    required super.id,
    required super.depositName,
    required super.feasibility,
    required super.economicStatus,
    required super.geoKnowledge,
    super.commodityGroup,
    super.commodity,
    super.miningStatus,
    super.unfcClassification,
    super.xUtm36s,
    super.yUtm36s,
    super.xWgs84,
    super.yWgs84,
    super.region,
    super.district,
    super.division,
    super.topoSheet250k,
    super.topoSheet100k,
    super.topoSheet50k,
    super.geologicalMap,
    super.access,
    super.geologicalDescription,
    super.geologicalTectonic,
    super.chronostratigraphicAge,
    super.hostRockLithology,
    super.regionalComment,
    super.generalDescription,
    super.shape,
    super.length,
    super.width,
    super.depth,
    super.dip,
    super.azimuth,
    super.strike,
    super.depositComment,
    super.mineralisationType,
    super.weatheringStatus,
    super.rocks,
    super.mineralDetails,
    super.resourceDetails,
    super.workDoneDetails,
    super.discoveryMethod,
    super.discoveryYear,
    super.workStartYear,
    super.stopYear,
    super.discoveryComment,
    super.archiveReports,
    super.siteComment,
    super.recordInfo,
  });

  factory DepositModel.fromJson(Map<String, dynamic> json) {
    return DepositModel(
      id: json['id'] as String,
      depositName: json['depositName'] as String,
      feasibility: json['feasibility'] as String,
      economicStatus: json['economicStatus'] as String,
      geoKnowledge: json['geoKnowledge'] as String,
      commodityGroup: json['commodityGroup'] as String?,
      commodity: json['commodity'] as String?,
      miningStatus: json['miningStatus'] as String?,
      unfcClassification: json['unfcClassification'] as String?,
      xUtm36s: json['xUtm36s'] as String?,
      yUtm36s: json['yUtm36s'] as String?,
      xWgs84: json['xWgs84'] as String?,
      yWgs84: json['yWgs84'] as String?,
      region: json['region'] as String?,
      district: json['district'] as String?,
      division: json['division'] as String?,
      topoSheet250k: json['topoSheet250k'] as String?,
      topoSheet100k: json['topoSheet100k'] as String?,
      topoSheet50k: json['topoSheet50k'] as String?,
      geologicalMap: json['geologicalMap'] as String?,
      access: json['access'] as String?,
      geologicalDescription: json['geologicalDescription'] as String?,
      geologicalTectonic: json['geologicalTectonic'] as String?,
      chronostratigraphicAge: json['chronostratigraphicAge'] as String?,
      hostRockLithology: json['hostRockLithology'] as String?,
      regionalComment: json['regionalComment'] as String?,
      generalDescription: json['generalDescription'] as String?,
      shape: json['shape'] as String?,
      length: json['length'] as String?,
      width: json['width'] as String?,
      depth: json['depth'] as String?,
      dip: json['dip'] as String?,
      azimuth: json['azimuth'] as String?,
      strike: json['strike'] as String?,
      depositComment: json['depositComment'] as String?,
      mineralisationType: json['mineralisationType'] as String?,
      weatheringStatus: json['weatheringStatus'] as String?,
      rocks: (json['rocks'] as List<dynamic>?)
              ?.map((e) => AssociatedRock.fromJson(e as Map<String, dynamic>))
              .toList() ??
          const [],
      mineralDetails: (json['mineralDetails'] as List<dynamic>?)
              ?.map((e) => MineralDetail.fromJson(e as Map<String, dynamic>))
              .toList() ??
          const [],
      resourceDetails: (json['resourceDetails'] as List<dynamic>?)
              ?.map((e) => ResourceDetail.fromJson(e as Map<String, dynamic>))
              .toList() ??
          const [],
      workDoneDetails: (json['workDoneDetails'] as List<dynamic>?)
              ?.map((e) => WorkDoneDetail.fromJson(e as Map<String, dynamic>))
              .toList() ??
          const [],
      discoveryMethod: json['discoveryMethod'] as String?,
      discoveryYear: json['discoveryYear'] as String?,
      workStartYear: json['workStartYear'] as String?,
      stopYear: json['stopYear'] as String?,
      discoveryComment: json['discoveryComment'] as String?,
      archiveReports: json['archiveReports'] as String?,
      siteComment: json['siteComment'] as String?,
      recordInfo: json['recordInfo'] as String?,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'depositName': depositName,
      'feasibility': feasibility,
      'economicStatus': economicStatus,
      'geoKnowledge': geoKnowledge,
      'commodityGroup': commodityGroup,
      'commodity': commodity,
      'miningStatus': miningStatus,
      'unfcClassification': unfcClassification,
      'xUtm36s': xUtm36s,
      'yUtm36s': yUtm36s,
      'xWgs84': xWgs84,
      'yWgs84': yWgs84,
      'region': region,
      'district': district,
      'division': division,
      'topoSheet250k': topoSheet250k,
      'topoSheet100k': topoSheet100k,
      'topoSheet50k': topoSheet50k,
      'geologicalMap': geologicalMap,
      'access': access,
      'geologicalDescription': geologicalDescription,
      'geologicalTectonic': geologicalTectonic,
      'chronostratigraphicAge': chronostratigraphicAge,
      'hostRockLithology': hostRockLithology,
      'regionalComment': regionalComment,
      'generalDescription': generalDescription,
      'shape': shape,
      'length': length,
      'width': width,
      'depth': depth,
      'dip': dip,
      'azimuth': azimuth,
      'strike': strike,
      'depositComment': depositComment,
      'mineralisationType': mineralisationType,
      'weatheringStatus': weatheringStatus,
      'rocks': rocks.map((e) => e.toJson()).toList(),
      'mineralDetails': mineralDetails.map((e) => e.toJson()).toList(),
      'resourceDetails': resourceDetails.map((e) => e.toJson()).toList(),
      'workDoneDetails': workDoneDetails.map((e) => e.toJson()).toList(),
      'discoveryMethod': discoveryMethod,
      'discoveryYear': discoveryYear,
      'workStartYear': workStartYear,
      'stopYear': stopYear,
      'discoveryComment': discoveryComment,
      'archiveReports': archiveReports,
      'siteComment': siteComment,
      'recordInfo': recordInfo,
    };
  }

  factory DepositModel.fromEntity(DepositEntity entity) {
    return DepositModel(
      id: entity.id,
      depositName: entity.depositName,
      feasibility: entity.feasibility,
      economicStatus: entity.economicStatus,
      geoKnowledge: entity.geoKnowledge,
      commodityGroup: entity.commodityGroup,
      commodity: entity.commodity,
      miningStatus: entity.miningStatus,
      unfcClassification: entity.unfcClassification,
      xUtm36s: entity.xUtm36s,
      yUtm36s: entity.yUtm36s,
      xWgs84: entity.xWgs84,
      yWgs84: entity.yWgs84,
      region: entity.region,
      district: entity.district,
      division: entity.division,
      topoSheet250k: entity.topoSheet250k,
      topoSheet100k: entity.topoSheet100k,
      topoSheet50k: entity.topoSheet50k,
      geologicalMap: entity.geologicalMap,
      access: entity.access,
      geologicalDescription: entity.geologicalDescription,
      geologicalTectonic: entity.geologicalTectonic,
      chronostratigraphicAge: entity.chronostratigraphicAge,
      hostRockLithology: entity.hostRockLithology,
      regionalComment: entity.regionalComment,
      generalDescription: entity.generalDescription,
      shape: entity.shape,
      length: entity.length,
      width: entity.width,
      depth: entity.depth,
      dip: entity.dip,
      azimuth: entity.azimuth,
      strike: entity.strike,
      depositComment: entity.depositComment,
      mineralisationType: entity.mineralisationType,
      weatheringStatus: entity.weatheringStatus,
      rocks: entity.rocks,
      mineralDetails: entity.mineralDetails,
      resourceDetails: entity.resourceDetails,
      workDoneDetails: entity.workDoneDetails,
      discoveryMethod: entity.discoveryMethod,
      discoveryYear: entity.discoveryYear,
      workStartYear: entity.workStartYear,
      stopYear: entity.stopYear,
      discoveryComment: entity.discoveryComment,
      archiveReports: entity.archiveReports,
      siteComment: entity.siteComment,
      recordInfo: entity.recordInfo,
    );
  }
}
